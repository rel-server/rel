func setupPgTypescript(srv *sw.SwServer) error {

	if ENABLE_TS_SCHEMAS != "" {
		srv.Router.Get("/scripts/{schema}.ts", func(w http.ResponseWriter, r *http.Request) {
			schema := chi.URLParam(r, "schema")

			if schema == "model" {
				w.Write([]byte(modelTs))
				return
			}

			var wr = &pg.TypescriptWriter{Writer: w, CurrentSchema: schema}

			var tables = make([]*pg.DBTable, 0)

			for _, table := range srv.Tables {
				if table.Schema == schema {
					tables = append(tables, table)
				}
			}

			var functions = make([]*pg.Function, 0)
			for _, function := range srv.Functions {
				if function.Schema == schema {
					functions = append(functions, function)
				}
			}

			sort.Slice(tables, func(i, j int) bool {
				return tables[i].Name < tables[j].Name
			})
			sort.Slice(functions, func(i, j int) bool {
				return functions[i].Name < functions[j].Name
			})

			pg.OutputTypescriptSchema(wr, schema, tables, functions)
		})
	}

	return nil
}
