var re_snal = regexp.MustCompile(`(^|_)([a-zA-Z$0-9])`)

type Col interface {
	TypeName() string
}

func decoderExp(col Col) string {
	var s = col.TypeName()

	if strings.HasPrefix(s, "json") {
		return "s.as_is"
	}

	if s == "text" || s == "varchar" {
		return "s.str"
	}

	if s == "bool" {
		return "s.str"
	}

	if strings.HasPrefix(s, "int") ||
		strings.HasPrefix(s, "float") ||
		s == "bigint" ||
		s == "numeric" {
		return "s.num"
	}

	if strings.HasPrefix(s, "timestamp") || s == "date" {
		return "s.date"
	}

	return fmt.Sprintf("p.Decoder(\"%s\")", s)
}

func JavascriptName(s string) string {

	if s == "text" {
		return "string"
	}

	if s == "bool" {
		return "boolean"
	}

	if strings.HasPrefix(s, "int") ||
		strings.HasPrefix(s, "float") ||
		s == "bigint" ||
		s == "numeric" {
		return "number"
	}

	if strings.HasPrefix(s, "timestamp") || s == "date" {
		return "Date"
	}

	if strings.HasPrefix(s, "json") {
		return "unknown"
	}

	return `p.PgType<"` + s + `">`
}

func ColumnJavascriptType(c Col) string {
	return JavascriptName(c.TypeName())
}

func SnakeCase(s string) string {
	return re_snal.ReplaceAllStringFunc(s, func(s string) string {
		if s[0] == '_' {
			return strings.ToUpper(s[1:])
		}
		return strings.ToUpper(s)
	})
}

func Preamble(srv *sw.SwServer, w io.Writer) {
	fmt.Fprintf(w, `/**
 * WARNING
 * THIS FILE WAS GENERATED BY goserver
 * ONLY EDIT CODE BETWEEN !impl and !end impl comments
 */

import { s } from "@salesway/pgts";
import * as p from "@salesway/pgts";

/** !impl FILE_HEADER **//** !end impl FILE_HEADER **/

`)
	for _, nsmp := range srv.Schemas {
		fmt.Fprintf(w, "export function %s() {}\n\n", nsmp)
	}

}

func writeFunctions(srv *sw.SwServer, w io.Writer) {
	for _, f := range srv.Functions {
		fmt.Fprintf(w, "%s.%s = function %s() {}\n\n", f.Schema, f.Name, f.Name)
	}
}

type PgColumn struct {
	*pg.DBColumn
}

func (p *PgColumn) TypeName() string {
	return p.Type
}

type PgComputedColumn struct {
	*pg.ComputedColumn
}

func (p *PgComputedColumn) TypeName() string {
	return p.ComputedColumn.Type
}

func writeClasses(srv *sw.SwServer, w io.Writer) {

	for _, table := range srv.Tables {
		var class_name = SnakeCase(table.Name)
		var full_name = table.Schema + "." + class_name
		fmt.Fprintf(w, "%s = class %s extends p.Model {\n", full_name, class_name)
		for _, column := range table.ColumnsInOrder {
			var c = &PgColumn{column}
			fmt.Fprintf(w, "  @(%s)", decoderExp(c))
			fmt.Fprintf(w, " %s: %s;\n", column.Name, ColumnJavascriptType(c))
		}

		if len(table.ComputedColumns) > 0 {
			fmt.Fprintf(w, "\n  // Computed Columns\n")
		}
		for _, column := range table.ComputedColumns {
			var c = &PgComputedColumn{column}
			fmt.Fprintf(w, "  @(%s.RO)", decoderExp(c))
			fmt.Fprintf(w, " %s: %s;\n", column.Name, ColumnJavascriptType(c))
		}

		fmt.Fprintf(w, "\n  /** !impl %s **//** !end impl %s **/\n}\n\n", full_name, full_name)
	}
}

